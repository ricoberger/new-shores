/** A minimal valid palette (every required group and role). */
function minimal(): Record<string, unknown> {
  const colors = (names: string[]) => Object.fromEntries(names.map((n) => [n, "#ABCDEF"]));
  return {
    version: 2,
    groups: {
      terrain: { description: "Ground.", colors: colors(["sand", "grass-a", "grass-b", "dry", "forest-floor", "mountain", "cliff"]) },
      water: { description: "Sea.", colors: colors(["shallows", "deep", "foam", "haze"]) },
      buildings: { description: "Materials.", colors: colors(["plaster", "ochre", "timber", "thatch", "terracotta", "slate", "stone", "brass"]) },
      ui: { description: "Chrome.", colors: { parchment: "#F1E6CC", "dark-wood": "#4A3421", brass: "#C9A24A", ink: "#2B2117" } },
      status: { description: "Status.", colors: { "paused-player": "#56B4E9" } },
      light: { description: "Light.", colors: { sun: "#FFF1D6", sky: "#9DB7D9" }, values: { "fill-ratio": 0.35 } },
    },
  };
}

describe("palette generator", () => {
  it("writes typed constants and CSS custom properties", () => {
    const { ts, css } = generatePalette(minimal());
    expect(ts).toContain("export const PALETTE_VERSION = 2;\n");
    expect(ts).toContain('/** Chrome. */\nexport const UI = {\n  parchment: "#F1E6CC",\n  dark_wood: "#4A3421",\n  brass: "#C9A24A",\n  ink: "#2B2117",\n} as const;\n');
    expect(ts).toContain('export const STATUS = {\n  paused_player: "#56B4E9",\n} as const;');
    expect(ts).toContain("export const LIGHT_VALUES = {\n  fill_ratio: 0.35,\n} as const;");
    expect(css.startsWith("/* Generated by scripts/gen-palette.mjs")).toBe(true);
    expect(css).toContain(":root {\n");
    expect(css).toContain("  --ns-ui-parchment: #F1E6CC;\n  --ns-ui-dark-wood: #4A3421;\n");
    expect(css).toContain("  --ns-light-fill-ratio: 0.35;\n");
    expect(css.endsWith("}\n")).toBe(true);
    // Deterministic.
    expect(generatePalette(minimal())).toEqual({ ts, css });
  });

  it("rejects malformed input", () => {
    const missingGroup = minimal();
    delete (missingGroup.groups as Record<string, unknown>).water;
    expect(() => generatePalette(missingGroup)).toThrow(/missing group "water"/);
    const missingRole = minimal();
    delete ((missingRole.groups as Record<string, { colors: Record<string, string> }>).ui as { colors: Record<string, string> }).colors.ink;
    expect(() => generatePalette(missingRole)).toThrow(/"ui" lacks "ink"/);
    const lower = minimal();
    ((lower.groups as Record<string, { colors: Record<string, string> }>).ui as { colors: Record<string, string> }).colors.ink = "#2b2117";
    expect(() => generatePalette(lower)).toThrow(/ui\.ink must be a 6-digit upper-case hex/);
    const short = minimal();
    ((short.groups as Record<string, { colors: Record<string, string> }>).ui as { colors: Record<string, string> }).colors.ink = "#FFF";
    expect(() => generatePalette(short)).toThrow(/6-digit/);
    const noDescription = minimal();
    ((noDescription.groups as Record<string, { description?: string }>).water as { description?: string }).description = "";
    expect(() => generatePalette(noDescription)).toThrow(/one-line description/);
    const badName = minimal();
    ((badName.groups as Record<string, { colors: Record<string, string> }>).status as { colors: Record<string, string> }).colors.Bad_Name = "#000000";
    expect(() => generatePalette(badName)).toThrow(/kebab-case/);
    expect(() => generatePalette({ ...minimal(), version: 0 })).toThrow(/version/);
    expect(() => generatePalette(null)).toThrow(/not an object/);
  });

  it("the committed files are the output for assets/palette.json", () => {
    const { ts, css } = generatePalette(JSON.parse(readFileSync(join(repo, "assets", "palette.json"), "utf8")));
    expect(readFileSync(join(here, "palette.ts"), "utf8")).toBe(ts);
    expect(readFileSync(join(here, "palette.css"), "utf8")).toBe(css);
  });
});

