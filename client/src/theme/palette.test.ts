/** Files under a directory (recursively). */
function files(dir: string): string[] {
  return readdirSync(dir).flatMap((n) => {
    const p = join(dir, n);
    return statSync(p).isDirectory() ? files(p) : [p];
  });
}

/**
 * Colour literals allowed outside the generated palette files (R4): the
 * unknown-terrain debug magenta.
 */
const ALLOWED = [{ file: "render/palette.ts", text: 'Color3.FromHexString("#FF00FF")' }];
const HEX = /#[0-9a-fA-F]{6}\b/;
const FUNC = /\b(rgba?|hsla?)\(/;

describe("colour literals", () => {
  it("render/, ui/ and display/status.ts read every colour from the palette", () => {
    const scanned = [...files(join(src, "render")), ...files(join(src, "ui")), join(src, "display", "status.ts")].filter((f) =>
      /\.(ts|tsx|css)$/.test(f),
    );
    expect(scanned.length).toBeGreaterThan(20);
    const found: string[] = [];
    for (const f of scanned) {
      const rel = relative(src, f).split("\\").join("/");
      readFileSync(f, "utf8")
        .split("\n")
        .forEach((line, i) => {
          if (!HEX.test(line) && !FUNC.test(line)) return;
          if (ALLOWED.some((a) => a.file === rel && line.includes(a.text))) return;
          found.push(`${rel}:${i + 1}: ${line.trim()}`);
        });
    }
    expect(found).toEqual([]);
  });
});
