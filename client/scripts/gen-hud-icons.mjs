// Generates client/src/theme/icons.ts — the HUD icon set as path data,
// recoloured with currentColor — from the pinned game-icons.net SVGs
// (CC BY 3.0) listed in assets/icons/icons.json, whose pinned licence text
// (assets/icons/LICENSE.txt) is checked too. No dependencies;
// deterministic output; exits non-zero on a missing file, a checksum
// mismatch or malformed input. Coordinates are rounded to 0.1 of the
// 512-unit view box (an adaptation noted in the credits). Run with
// `npm run gen:hud-icons`; the output is committed and CI checks drift.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const KEY = /^(good|need|status|category|tool):[a-z0-9_-]+$/;
const BACKGROUND = "M0 0h512v512H0z";

/** Rounds the coordinates of a path to 0.1; paths with arcs (compact flags) are kept as they are. */
export function roundPath(d) {
  if (/[aA]/.test(d)) return d;
  const tokens = d.match(/[a-zA-Z]|-?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?/g) ?? [];
  let out = "";
  let prevNumber = false;
  for (const t of tokens) {
    if (/^[a-zA-Z]$/.test(t)) {
      out += t;
      prevNumber = false;
      continue;
    }
    let n = (Math.round(Number(t) * 10) / 10).toString();
    if (n === "-0") n = "0";
    n = n.replace(/^(-?)0\./, "$1.");
    if (prevNumber && !n.startsWith("-")) out += " ";
    out += n;
    prevNumber = true;
  }
  return out;
}

/** The icon paths (`d` of every non-background path, joined) of an SVG document. */
export function svgPaths(svg) {
  const ds = [...svg.matchAll(/<path\b[^>]*\bd="([^"]+)"/g)].map((m) => m[1]).filter((d) => d !== BACKGROUND);
  if (ds.length === 0) throw new Error("icons: SVG without an icon path");
  if (/<(circle|rect|ellipse|polygon|polyline|line|g\b[^>]*transform)/.test(svg)) throw new Error("icons: SVG with shapes other than paths");
  return ds.join(" ");
}

/**
 * Validates icons.json against the SVG files (via `read(file)`) and the
 * licence text (via `readLicense(file)`) and returns the generated
 * TypeScript text. Throws an Error naming the first problem.
 */
export function generateIcons(manifest, read, readLicense) {
  if (typeof manifest !== "object" || manifest === null || typeof manifest.icons !== "object" || manifest.icons === null) {
    throw new Error("icons: manifest without icons");
  }
  if (typeof manifest.license !== "string" || manifest.license === "") throw new Error("icons: manifest without a license");
  const lic = manifest.licenseFile;
  if (typeof lic?.file !== "string" || typeof lic.sha256 !== "string") throw new Error("icons: manifest without a licence file");
  if (createHash("sha256").update(readLicense(lic.file)).digest("hex") !== lic.sha256) throw new Error(`icons: checksum mismatch for ${lic.file}`);
  const unique = [];
  const index = new Map();
  const entries = [];
  const authors = new Set();
  for (const [key, icon] of Object.entries(manifest.icons)) {
    if (!KEY.test(key)) throw new Error(`icons: bad key ${JSON.stringify(key)}`);
    if (typeof icon?.file !== "string" || !/^[a-z0-9-]+\.svg$/.test(icon.file)) throw new Error(`icons: ${key} has a bad file name`);
    if (typeof icon.author !== "string" || icon.author === "") throw new Error(`icons: ${key} has no author`);
    const data = read(icon.file);
    const sum = createHash("sha256").update(data).digest("hex");
    if (sum !== icon.sha256) throw new Error(`icons: checksum mismatch for ${icon.file} (${key})`);
    if (!index.has(icon.file)) {
      index.set(icon.file, unique.length);
      unique.push(roundPath(svgPaths(data.toString("utf8"))));
    }
    entries.push([key, index.get(icon.file)]);
    authors.add(icon.author);
  }
  for (const k of ["good:_fallback", "need:_fallback"]) if (!entries.some(([key]) => key === k)) throw new Error(`icons: missing ${k}`);
  entries.sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));
  const lines = [
    "// Generated by scripts/gen-hud-icons.mjs from assets/icons — do not edit.",
    "// Icons by game-icons.net contributors, CC BY 3.0 (see README credits);",
    "// coordinates rounded to 0.1, recoloured with currentColor.",
    "",
    "/** View box size of every icon path (0 0 512 512). */",
    "export const ICON_VIEWBOX = 512;",
    "",
    "const P = [",
    ...unique.map((d) => `  ${JSON.stringify(d)},`),
    "] as const;",
    "",
    "/** Path data per icon key (kind:id). */",
    "export const ICON_PATHS: Readonly<Record<string, string>> = {",
    ...entries.map(([k, i]) => `  ${JSON.stringify(k)}: P[${i}],`),
    "};",
    "",
    "/** Icon authors (game-icons.net), for the credits. */",
    `export const ICON_AUTHORS: readonly string[] = ${JSON.stringify([...authors].sort())};`,
    "",
    `export const ICON_LICENSE = ${JSON.stringify(manifest.license)};`,
    "",
  ];
  return lines.join("\n");
}

function main() {
  const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
  const dir = join(root, "assets", "icons");
  const manifest = JSON.parse(readFileSync(join(dir, "icons.json"), "utf8"));
  const ts = generateIcons(
    manifest,
    (f) => readFileSync(join(dir, "game-icons", f)),
    (f) => readFileSync(join(dir, f)),
  );
  const out = join(root, "client", "src", "theme", "icons.ts");
  writeFileSync(out, ts);
  console.log(`${Object.keys(manifest.icons).length} icons written to ${out}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    main();
  } catch (err) {
    console.error(err.message);
    process.exit(1);
  }
}
