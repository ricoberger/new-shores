	// farmChoices is the number of farm sites that pass their trial among
	// which site picks the one with the least exposed grass edge, weighed
	// by packWeight.
	farmChoices = 12
	packWeight  = 1.0
	// reachSlack (percent) is the coverage a Reach plot may give up for
	// fewer grass tiles.
	reachSlack = 60
	// tilesPerHouse caps a quarter's house land per house it holds.
	tilesPerHouse = 26
	// anchorNear bounds the roomiest land around a quarter's Near tile.
	anchorNear = 16
	// maxCutOff is the open land a placement may cut off the roads.
	maxCutOff = 12
	// maxHouseTrials bounds the house sites tried per house.
	maxHouseTrials = 60
	// siteRounds bounds the batches of MaxCandidates sites tried.
	siteRounds = 8
	// reserveMinutes is how long a gold-spending step must not lead to an
